function parseLsTree(buffer) {
  const text = buffer.toString("utf8");
  const entries = [];
  for (const record of text.split("\0")) {
    if (record === "") continue;
    const tab = record.indexOf("\t");
    const meta = record.slice(0, tab).split(" ");
    entries.push({ mode: meta[0], type: meta[1], sha: meta[2], path: record.slice(tab + 1) });
  }
  return entries;
}

export function parseSkillFrontmatterName(skillMarkdown) {
  const frontmatter = skillMarkdown.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const name = frontmatter?.[1].match(/^name:\s*["']?(.+?)["']?\s*$/m)?.[1];
  return name ?? null;
}

// ---------------------------------------------------------------------------
// 过滤（§10.3）：only 先包含，exclude 最终否决；大小写敏感 POSIX 路径
// ---------------------------------------------------------------------------

function filterMatches(pattern, skill) {
  if (pattern.endsWith("/")) {
    return skill.sourcePath.startsWith(pattern) || skill.sourcePath === pattern.slice(0, -1);
  }
  const base = skill.sourcePath.includes("/") ? skill.sourcePath.slice(skill.sourcePath.lastIndexOf("/") + 1) : skill.sourcePath;
  return skill.name === pattern || base === pattern;
}

export function selectedByFilters(skill, source) {
  if (source.only && !source.only.some((pattern) => filterMatches(pattern, skill))) return false;
  if (source.exclude && source.exclude.some((pattern) => filterMatches(pattern, skill))) return false;
  return true;
}

// ---------------------------------------------------------------------------
// 来源 staging：fetch → resolve → discover → 校验 → 摘要 → 许可证（全程零目标修改）
// ---------------------------------------------------------------------------

function refspecOf(track) {
  if (track.kind === "branch") return `refs/heads/${track.value}`;
  if (track.kind === "tag") return `refs/tags/${track.value}`;
  return track.value;
}

async function openBareRepo({ fs, git, tmpParent, label, source }) {
  const repoDir = join(tmpParent, label);
  await fs.mkdir(repoDir, { recursive: true });
  try {
    await git(["init", "-q", "--bare", repoDir]);
    return repoDir;
  } catch (error) {
    throw new SyncError(ERR.fetchFailed, `source "${source.id}": cannot init temp repo: ${error.message}; fix: ensure git is installed.`);
  }
}

async function fetchInto({ git, repoDir, source, refspec }) {
  try {
    await git(["-C", repoDir, "fetch", "-q", "--depth", "1", source.repo, refspec]);
  } catch (error) {
    throw new SyncError(
      ERR.fetchFailed,
      `source "${source.id}" (${source.repo}, ${source.track.kind} "${source.track.value}"): fetch failed: ${error.message}; fix: check network, Git credentials and that the ref exists.`,
    );
  }
}

async function resolveFetchHead({ git, repoDir, source }) {
  let resolved;
  try {
    resolved = (await git(["-C", repoDir, "rev-parse", "FETCH_HEAD^{commit}"])).toString("utf8").trim();
  } catch (error) {
    throw new SyncError(
      ERR.fetchFailed,
      `source "${source.id}": ${source.track.kind} "${source.track.value}" does not resolve to a commit object: ${error.message}; fix: point track at a branch, tag or commit.`,
    );
  }
  if (!PINNED_SHA.test(resolved)) {
    throw new SyncError(ERR.fetchFailed, `source "${source.id}": resolver returned non-SHA ${JSON.stringify(resolved)}; fix: report this as a sync bug.`);
  }
  return resolved;
}

// 按 ls-tree 的 blob SHA 直接读取原始字节（DSC-008）。不用 git archive：
// archive 会应用 export-ignore（丢文件）与 export-subst（改字节），破坏 tree 保真。
async function readBlobs({ git, repoDir, source, items }) {
  const blobs = new Map();
  const CHUNK = 16;
  for (let offset = 0; offset < items.length; offset += CHUNK) {
    await Promise.all(
      items.slice(offset, offset + CHUNK).map(async (item) => {
        try {
          blobs.set(item.sha, await git(["-C", repoDir, "cat-file", "blob", item.sha]));
        } catch (error) {
          throw new SyncError(
            ERR.fetchFailed,
            `source "${source.id}": cannot read blob ${item.sha.slice(0, 12)}: ${error.message}; fix: re-run with --force or report a sync bug.`,
          );
        }
      }),
    );
  }
  return blobs;
}

// 发现 + 过滤 + 校验 + 摘要 + 许可证；输入为已解析 commit，输出物化所需的全部字节。
async function stageSourceContent({ fs, git, repoDir, source, resolved }) {
  if (source.path !== ".") {
    const probe = parseLsTree(await git(["-C", repoDir, "ls-tree", "-z", resolved, "--", source.path]));
    if (probe.length === 0 || probe[0].type !== "tree") {
      throw new SyncError(
        ERR.pathMissing,
        `source "${source.id}": path "${source.path}" does not exist in ${source.repo} @ ${resolved.slice(0, 12)}; fix: correct the path in ${MANIFEST_REL}.`,
      );
    }
  }
  const treeArgs = source.path === "." ? ["-C", repoDir, "ls-tree", "-r", "-z", resolved] : ["-C", repoDir, "ls-tree", "-r", "-z", resolved, "--", source.path];
  const tree = parseLsTree(await git(treeArgs));
  const prefix = source.path === "." ? "" : `${source.path}/`;
  const relativize = (path) => (prefix === "" ? path : path.slice(prefix.length));

  // 发现：含 SKILL.md 的目录即 Skill，不再下钻（DSC-001）。
  const skillMdByDir = new Map();
  for (const entry of tree) {
    if (entry.type !== "blob") continue;
    const rel = relativize(entry.path);
    const base = rel.includes("/") ? rel.slice(rel.lastIndexOf("/") + 1) : rel;
    if (base !== "SKILL.md") continue;
    const dir = rel.includes("/") ? rel.slice(0, rel.lastIndexOf("/")) : ".";
    skillMdByDir.set(dir, { entry, rel });
  }
  const candidates = [...skillMdByDir.keys()].sort();
  const skillDirs = candidates.filter((dir) => !candidates.some((other) => other !== dir && dir.startsWith(`${other}/`)));
  if (skillDirs.length === 0) {
    throw new SyncError(
      ERR.noneSelected,
      `source "${source.id}": no directory with SKILL.md found under "${source.path}"; fix: correct path or only/exclude in ${MANIFEST_REL}.`,
    );
  }

  // frontmatter 身份（DSC-002：不得回退目录名）。
  const mdBlobs = await readBlobs({ git, repoDir, source, items: skillDirs.map((dir) => skillMdByDir.get(dir).entry) });
  let discovered = skillDirs.map((dir) => {
    const { entry, rel } = skillMdByDir.get(dir);
    const name = parseSkillFrontmatterName(mdBlobs.get(entry.sha).toString("utf8"));
    if (name === null || name === "") {
      throw new SyncError(
        ERR.frontmatterInvalid,
        `source "${source.id}": ${rel} has no parseable frontmatter "name"; fix: add "---\\nname: <skill>\\n---" upstream or exclude the directory.`,
      );
    }
    return { name, sourcePath: dir };
  });

  discovered = discovered.filter((skill) => selectedByFilters(skill, source));
  if (discovered.length === 0) {
    throw new SyncError(
      ERR.noneSelected,
      `source "${source.id}": only/exclude filters leave no skills under "${source.path}"; fix: adjust only/exclude in ${MANIFEST_REL}.`,
    );
  }
  for (const skill of discovered) {
    if (!SAFE_SKILL_NAME.test(skill.name) || RESERVED_SKILL_NAMES.has(skill.name)) {
      throw new SyncError(
        ERR.nameInvalid,
        `source "${source.id}": skill name "${skill.name}" (at "${skill.sourcePath}") is illegal or reserved; fix: match [A-Za-z0-9._-]+ and avoid ".", "..", "${SOURCES_DIRNAME}", "${STAGING_DIRNAME}".`,
      );
    }
  }

  // 选中 tree 安全校验（DSC-007：symlink / gitlink 一律拒绝）。
  const selectedDirs = discovered.map((skill) => skill.sourcePath);
  for (const entry of tree) {
    const rel = relativize(entry.path);
    const inside = selectedDirs.some((dir) => (dir === "." ? true : rel === dir || rel.startsWith(`${dir}/`)));
    if (!inside) continue;
    if (entry.mode === "120000" || entry.mode === "160000") {
      const kind = entry.mode === "120000" ? "symlink" : "git submodule";
      throw new SyncError(
        ERR.treeUnsafe,
        `source "${source.id}": selected tree contains ${kind} at "${rel}"; fix: remove it upstream or exclude the affected skill.`,
      );
    }
  }

  // 全量物化字节 + tree digest（DSC-008：字节与可执行位完整保留）。
  const blobItems = [];
  const skillEntrySpecs = discovered.map((skill) => {
    const dirPrefix = skill.sourcePath === "." ? "" : `${skill.sourcePath}/`;
    const entries = [];
    for (const entry of tree) {
      if (entry.type !== "blob" || entry.mode === "120000" || entry.mode === "160000") continue;
      const rel = relativize(entry.path);
      if (dirPrefix !== "" && !rel.startsWith(dirPrefix)) continue;
      const path = dirPrefix === "" ? rel : rel.slice(dirPrefix.length);
      if (path === "") continue;
      const item = { path, executable: (parseInt(entry.mode, 8) & 0o111) !== 0, sha: entry.sha };
      entries.push(item);
      blobItems.push(item);
    }
    return { skill, entries };
  });
  const blobs = await readBlobs({ git, repoDir, source, items: blobItems });
  const skills = skillEntrySpecs.map(({ skill, entries }) => {
    const full = entries.map((entry) => ({ path: entry.path, executable: entry.executable, bytes: blobs.get(entry.sha) }));
    return { name: skill.name, sourcePath: skill.sourcePath, treeDigest: digestEntries(full), entries: full };
  });

  // 仓库级许可证（LCK-008 / docs/adr/0003）：只复制，不推断 SPDX。
  const rootListing = parseLsTree(await git(["-C", repoDir, "ls-tree", "-z", resolved]));
  const licenseEntries = rootListing
    .filter((entry) => entry.type === "blob" && !entry.path.includes("/") && /^license/i.test(entry.path))
    .sort((a, b) => (a.path < b.path ? -1 : 1));
  const licenseBlobs = await readBlobs({ git, repoDir, source, items: licenseEntries });
  const licenseFiles = licenseEntries.map((entry) => ({
    path: entry.path,
    sha256: sha256Hex(licenseBlobs.get(entry.sha)),
    bytes: licenseBlobs.get(entry.sha),
  }));
  return { spec: source, resolved, skills, licenseFiles, licenseDeclared: licenseEntries.length > 0 };
}

// 解析 track（update）或直接定位 resolved commit（sync 修复），返回可物化的来源内容。
async function stageSource({ fs, git, tmpParent, index, source, pinnedResolved }) {
  const repoDir = await openBareRepo({ fs, git, tmpParent, label: `source-${index}`, source });
  const refspec = pinnedResolved ?? refspecOf(source.track);
  await fetchInto({ git, repoDir, source, refspec });
  const resolved = await resolveFetchHead({ git, repoDir, source });
  if (pinnedResolved && resolved !== pinnedResolved) {
    throw new SyncError(
      ERR.fetchFailed,
      `source "${source.id}": fetched ${resolved} but lock requires ${pinnedResolved}; fix: check that the repository still serves the locked commit.`,
    );
  }
  return stageSourceContent({ fs, git, repoDir, source, resolved });
}

// ---------------------------------------------------------------------------
// 本地状态评估：READY / drift 分类（普通 sync 的零网络判定）
// ---------------------------------------------------------------------------

async function assessLocalState({ root, fs, lock }) {
  const skillsRootAbs = join(root, lock.skillsRoot);
  const driftSkills = [];
  const keptSkills = [];
  for (const source of lock.sources) {
    for (const skill of source.skills) {
      const target = join(skillsRootAbs, skill.name);
      const digest = (await pathExists(fs, target)) ? await digestDiskDirectory(target, fs) : null;
      if (digest === skill.treeDigest) keptSkills.push({ source, skill });
      else driftSkills.push({ source, skill, missing: !(await pathExists(fs, target)) });
    }
  }
  const licenseIssues = [];
  for (const source of lock.sources) {
    for (const file of source.licenseFiles) {
      const target = join(root, file.localPath);
      let ok = false;
      try {
        ok = sha256Hex(await fs.readFile(target)) === file.sha256;
      } catch {
        ok = false;
      }
      if (!ok) licenseIssues.push({ source, file });
    }
  }
  const allNames = lock.sources.flatMap((source) => source.skills.map((skill) => skill.name));
  const gitignorePath = join(skillsRootAbs, ".gitignore");
  let gitignoreOk = false;
  try {
    gitignoreOk = (await fs.readFile(gitignorePath, "utf8")) === expectedGitignore(allNames);
  } catch {
    gitignoreOk = false;
  }
  const ready = driftSkills.length === 0 && licenseIssues.length === 0 && gitignoreOk;
  return { ready, driftSkills, keptSkills, licenseIssues, gitignoreOk };
}


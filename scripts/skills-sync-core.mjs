// 检测 .agent/skills/ 中的本地 Skill 与 synced skills 的名称冲突（DSC-009）。
// 遵循 Violin 模式：本地优先，冲突时报告 diagnostic（WARNING），不阻断同步。
async function checkAgentSkillsConflicts({ root, fs, syncedSkillNames }) {
  const agentSkillsRoot = join(root, ".agent", "skills");
  if (!(await pathExists(fs, agentSkillsRoot))) return [];
  const warnings = [];
  let entries;
  try { entries = await fs.readdir(agentSkillsRoot); } catch { return []; }
  for (const entry of entries) {
    if (entry.startsWith(".")) continue;
    const skillDir = join(agentSkillsRoot, entry);
    let stat;
    try { stat = await fs.lstat(skillDir); } catch { continue; }
    if (!stat.isDirectory()) continue;
    const skillMd = join(skillDir, "SKILL.md");
    let content;
    try { content = await fs.readFile(skillMd, "utf8"); } catch { continue; }
    const name = parseSkillFrontmatterName(content);
    if (!name || name === "") continue;
    if (syncedSkillNames.has(name)) {
      warnings.push({ name, localDir: `.agent/skills/${entry}` });
    }
  }
  return warnings;
}

// Commit：staging 全部成功后一次性应用（adr/0001；中断仅产生 drift）
// ---------------------------------------------------------------------------

async function writeStagedTree({ fs, stagingRoot, stagedSources }) {
  for (const staged of stagedSources) {
    for (const skill of staged.skills) {
      const base = join(stagingRoot, "skills", skill.name);
      for (const entry of skill.entries) {
        const target = join(base, ...entry.path.split("/"));
        await fs.mkdir(dirname(target), { recursive: true });
        await fs.writeFile(target, entry.bytes);
        await fs.chmod(target, entry.executable ? 0o755 : 0o644);
      }
    }
    if (staged.licenseFiles.length > 0) {
      const licenseBase = join(stagingRoot, "sources", staged.spec.id, "licenses");
      for (const file of staged.licenseFiles) {
        const target = join(licenseBase, ...file.path.split("/"));
        await fs.mkdir(dirname(target), { recursive: true });
        await fs.writeFile(target, file.bytes);
        await fs.chmod(target, 0o644);
      }
    }
  }
}

async function commitTransaction({ root, fs, lock, priorLock, stagedBySourceId, writeLock, allowPrune, events }) {
  const skillsRootAbs = join(root, lock.skillsRoot);
  const stagingRoot = join(skillsRootAbs, STAGING_DIRNAME);
  await fs.rm(stagingRoot, { recursive: true, force: true });
  const stagedSources = [...stagedBySourceId.values()];
  await writeStagedTree({ fs, stagingRoot, stagedSources });

  await fs.mkdir(skillsRootAbs, { recursive: true });

  // 剪枝：只允许 prior lock 明确拥有且新 lock 不再引用的路径（MAT-009）；路径锚定在 prior 根。
  if (allowPrune && priorLock) {
    const priorRootAbs = join(root, priorLock.skillsRoot);
    const newNames = new Set(lock.sources.flatMap((source) => source.skills.map((skill) => skill.name)));
    const newIds = new Set(lock.sources.map((source) => source.id));
    for (const source of priorLock.sources) {
      for (const skill of source.skills) {
        if (!newNames.has(skill.name)) {
          await fs.rm(join(priorRootAbs, skill.name), { recursive: true, force: true });
          events.push({ type: "PRUNED", name: skill.name });
        }
      }
      if (!newIds.has(source.id)) {
        await fs.rm(join(priorRootAbs, SOURCES_DIRNAME, source.id), { recursive: true, force: true });
      }
    }
  }

  // lock 先落盘：commit 中断只产生“新 lock + 旧目录”的 drift，普通 sync 可自愈（adr/0001）。
  if (writeLock) {
    const serialized = serializeLock(lock);
    const lockPath = join(root, LOCK_REL);
    let current = null;
    try {
      current = await fs.readFile(lockPath, "utf8");
    } catch {
      current = null;
    }
    if (current !== serialized) {
      await fs.mkdir(join(root, ".agents"), { recursive: true });
      await fs.writeFile(lockPath, serialized);
    }
  }

  for (const source of lock.sources) {
    const staged = stagedBySourceId.get(source.id);
    for (const skill of source.skills) {
      const target = join(skillsRootAbs, skill.name);
      const diskDigest = (await pathExists(fs, target)) ? await digestDiskDirectory(target, fs) : null;
      if (diskDigest === skill.treeDigest) {
        events.push({ type: "KEPT", name: skill.name, resolved: source.resolved });
        continue;
      }
      if (!staged) {
        throw new SyncError(
          ERR.verifyFailed,
          `skill "${skill.name}" drifted but source "${source.id}" was not staged; fix: re-run skills-sync --force.`,
        );
      }
      await fs.rm(target, { recursive: true, force: true });
      await fs.rename(join(stagingRoot, "skills", skill.name), target);
      events.push({ type: "SYNCED", name: skill.name, resolved: source.resolved });
    }
    if (staged) {
      const licenseBase = join(skillsRootAbs, SOURCES_DIRNAME, source.id, "licenses");
      await fs.rm(licenseBase, { recursive: true, force: true });
      if (staged.licenseFiles.length > 0) {
        await fs.mkdir(dirname(licenseBase), { recursive: true });
        await fs.rename(join(stagingRoot, "sources", source.id, "licenses"), licenseBase);
      } else {
        await fs.rm(join(skillsRootAbs, SOURCES_DIRNAME, source.id), { recursive: true, force: true });
      }
    }
  }

  // gitignore 最后写；内容为受管名字的确定函数（IGN-003）。
  const allNames = lock.sources.flatMap((source) => source.skills.map((skill) => skill.name));
  const gitignorePath = join(skillsRootAbs, ".gitignore");
  const expected = expectedGitignore(allNames);
  let currentGitignore = null;
  try {
    currentGitignore = await fs.readFile(gitignorePath, "utf8");
  } catch {
    currentGitignore = null;
  }
  if (currentGitignore !== expected) {
    await fs.writeFile(gitignorePath, expected);
  }

  // 端到端校验（MAT-008）：commit 后重算摘要，失败按 drift 留给后续 sync。
  for (const source of lock.sources) {
    for (const skill of source.skills) {
      const digest = await digestDiskDirectory(join(skillsRootAbs, skill.name), fs);
      if (digest !== skill.treeDigest) {
        throw new SyncError(
          ERR.verifyFailed,
          `skill "${skill.name}" digest mismatch after materialize (expected ${skill.treeDigest.slice(0, 12)}); fix: re-run skills-sync to repair the drifted directory.`,
        );
      }
    }
  }
  await fs.rm(stagingRoot, { recursive: true, force: true });
}


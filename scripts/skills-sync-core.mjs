// 来源期望状态的 canonical 形态：spec 相等性（SRC-005）与 lock 记录都以此为准。
export function canonicalSourceSpec(source) {
  return {
    id: source.id,
    repo: source.repo,
    path: source.path,
    track: { kind: source.track.kind, value: source.track.value },
    ...(source.only ? { only: [...source.only].sort() } : {}),
    ...(source.exclude ? { exclude: [...source.exclude].sort() } : {}),
  };
}

export function sourceSpecEqual(manifestSource, lockSource) {
  return JSON.stringify(canonicalSourceSpec(manifestSource)) === JSON.stringify(canonicalSourceSpec(lockSource));
}

const LOCK_SOURCE_FIELDS = new Set(["id", "repo", "path", "track", "only", "exclude", "resolved", "licenseFiles", "skills"]);

export function parseLockValue(value) {
  if (!isRecord(value)) throw new SyncError(ERR.lockInvalid, `${LOCK_REL} must be a JSON object; fix: run skills-sync --update to regenerate it.`, 2);
  if (value.version !== 2) {
    throw new SyncError(
      ERR.manifestVersion,
      `${LOCK_REL} version must be 2, got ${JSON.stringify(value.version)}; v1 locks are not upgraded in place — fix: save your worktree, replace the control plane and run skills-sync --update once.`,
      2,
    );
  }
  if (!isNonEmptyString(value.skillsRoot)) {
    throw new SyncError(ERR.lockInvalid, `${LOCK_REL} is missing skillsRoot; fix: run skills-sync --update.`, 2);
  }
  let skillsRoot;
  try {
    skillsRoot = normalizeRelativePath(value.skillsRoot, "lock skillsRoot", { allowDot: false });
  } catch (error) {
    throw new SyncError(ERR.lockInvalid, `${LOCK_REL}: ${error.message} fix: run skills-sync --update to regenerate the lock.`, 2);
  }
  if (!Array.isArray(value.sources)) {
    throw new SyncError(ERR.lockInvalid, `${LOCK_REL} sources must be an array; fix: run skills-sync --update.`, 2);
  }
  const ids = new Set();
  const names = new Map();
  const sources = value.sources.map((entry, index) => {
    const at = `lock sources[${index}]`;
    const invalid = (problem) => new SyncError(ERR.lockInvalid, `${at}: ${problem}; fix: run skills-sync --update to regenerate the lock.`, 2);
    if (!isRecord(entry)) throw invalid("must be an object");
    for (const key of Object.keys(entry)) {
      if (!LOCK_SOURCE_FIELDS.has(key)) throw invalid(`unknown field "${key}"`);
    }
    if (!isNonEmptyString(entry.id) || !SOURCE_ID.test(entry.id)) throw invalid("id is missing or illegal");
    if (ids.has(entry.id)) throw invalid(`duplicate source id "${entry.id}"`);
    ids.add(entry.id);
    if (!isNonEmptyString(entry.repo)) throw invalid("repo is missing");
    if (!isNonEmptyString(entry.path)) throw invalid("path is missing");
    if (!isRecord(entry.track) || !TRACK_KINDS.has(entry.track.kind) || !isNonEmptyString(entry.track.value)) throw invalid("track is missing or illegal");
    if (!PINNED_SHA.test(entry.resolved ?? "")) throw invalid(`resolved must be a 40-char lowercase SHA, got ${JSON.stringify(entry.resolved)}`);
    for (const field of ["only", "exclude"]) {
      if (entry[field] !== undefined && (!Array.isArray(entry[field]) || entry[field].some((item) => !isNonEmptyString(item)))) {
        throw invalid(`${field} must be an array of non-empty strings`);
      }
    }
    if (!Array.isArray(entry.licenseFiles)) throw invalid("licenseFiles must be an array");
    const licenseFiles = entry.licenseFiles.map((file, fileIndex) => {
      if (!isRecord(file) || !isNonEmptyString(file.path) || !/^[0-9a-f]{64}$/.test(file.sha256 ?? "") || !isNonEmptyString(file.localPath)) {
        throw invalid(`licenseFiles[${fileIndex}] must declare path, sha256 and localPath`);
      }
      if (file.path.includes("/") || file.path === "." || file.path === "..") {
        throw invalid(`licenseFiles[${fileIndex}].path must be a repository-root file name`);
      }
      if (file.localPath !== licenseLocalPath(skillsRoot, entry.id, file.path)) {
        throw invalid(`licenseFiles[${fileIndex}].localPath must be "${licenseLocalPath(skillsRoot, entry.id, file.path)}"`);
      }
      return { path: file.path, sha256: file.sha256, localPath: file.localPath };
    });
    if (!Array.isArray(entry.skills) || entry.skills.length === 0) throw invalid("skills must be a non-empty array");
    const skills = entry.skills.map((skill, skillIndex) => {
      if (
        !isRecord(skill) ||
        !SAFE_SKILL_NAME.test(skill.name ?? "") ||
        RESERVED_SKILL_NAMES.has(skill.name) ||
        !isNonEmptyString(skill.sourcePath) ||
        !/^[0-9a-f]{64}$/.test(skill.treeDigest ?? "")
      ) {
        throw invalid(`skills[${skillIndex}] must declare name, sourcePath and treeDigest`);
      }
      if (skill.sourcePath !== "." && (skill.sourcePath.startsWith("/") || skill.sourcePath.split("/").some((part) => part === ".." || part === ""))) {
        throw invalid(`skills[${skillIndex}].sourcePath must be a safe repository-relative path`);
      }
      const owner = names.get(skill.name);
      if (owner) throw invalid(`skill name "${skill.name}" is claimed by both "${owner}" and "${entry.id}"`);
      names.set(skill.name, entry.id);
      return { name: skill.name, sourcePath: skill.sourcePath, treeDigest: skill.treeDigest };
    });
    return {
      ...canonicalSourceSpec(entry),
      resolved: entry.resolved,
      licenseFiles,
      skills,
    };
  });
  return { skillsRoot, sources };
}

export function parseLockText(raw) {
  let value;
  try {
    value = JSON.parse(raw);
  } catch (error) {
    throw new SyncError(ERR.lockInvalid, `${LOCK_REL} is not valid JSON: ${error.message}; fix: repair it or run skills-sync --update.`, 2);
  }
  return parseLockValue(value);
}

// 许可证物化位置（MAT-010）：skillsRoot/.sources/<source-id>/licenses/。
export function licenseLocalPath(skillsRoot, sourceId, repoPath) {
  return `${skillsRoot}/${SOURCES_DIRNAME}/${sourceId}/licenses/${repoPath}`;
}

// 确定性 lock 序列化：sources 按 id、skills 按 name、licenses 按 path 排序；无时间戳与绝对路径。
export function buildLock({ skillsRoot, resolvedSources }) {
  const sources = resolvedSources
    .map((entry) => ({
      ...canonicalSourceSpec(entry.spec),
      resolved: entry.resolved,
      licenseFiles: [...entry.licenseFiles]
        .map((file) => ({ path: file.path, sha256: file.sha256, localPath: licenseLocalPath(skillsRoot, entry.spec.id, file.path) }))
        .sort((a, b) => (a.path < b.path ? -1 : 1)),
      skills: [...entry.skills]
        .map((skill) => ({ name: skill.name, sourcePath: skill.sourcePath, treeDigest: skill.treeDigest }))
        .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0)),
    }))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return { version: 2, skillsRoot, sources };
}

export function serializeLock(lock) {
  return JSON.stringify(lock, null, 2) + "\n";
}

// 生成的 gitignore：根锚定受管目录 + provenance/staging，永不使用吞掉内置 Skill 的通配（IGN-001/002/003）。
export function expectedGitignore(skillNames) {
  const lines = [GITIGNORE_HEADER, ...[...skillNames].sort().map((name) => `/${name}/`), `/${SOURCES_DIRNAME}/`, `/${STAGING_DIRNAME}/`, ""];
  return lines.join("\n");
}


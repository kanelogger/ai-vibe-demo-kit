// 主流程：sync / update
// ---------------------------------------------------------------------------

async function readManifestIfPresent({ root, fs }) {
  const manifestPath = join(root, MANIFEST_REL);
  if (!(await pathExists(fs, manifestPath))) return null;
  return parseManifestText(await fs.readFile(manifestPath, "utf8"));
}

async function readLockIfPresent({ root, fs }) {
  const lockPath = join(root, LOCK_REL);
  if (!(await pathExists(fs, lockPath))) return null;
  return parseLockText(await fs.readFile(lockPath, "utf8"));
}

function specsMatch(manifest, lock) {
  if (!manifest || !lock) return false;
  if (manifest.skillsRoot !== lock.skillsRoot) return false;
  if (manifest.sources.length !== lock.sources.length) return false;
  const lockById = new Map(lock.sources.map((source) => [source.id, source]));
  return manifest.sources.every((source) => {
    const locked = lockById.get(source.id);
    return locked && sourceSpecEqual(source, locked);
  });
}

// runSkillsSync：协议无关入口（MCP-001/002）。返回 { status, events, lock }；失败抛 SyncError。
export async function runSkillsSync({ root, update = false, force = false, fs = defaultFs, git = createNodeGit() }) {
  const events = [];
  const manifest = await readManifestIfPresent({ root, fs });
  const priorLock = await readLockIfPresent({ root, fs });

  // UNCONFIGURED：无清单，或 sources 为空且无 v2 lock（§9.2；内置 Skill 永不被触碰）。
  if (!manifest || (manifest.sources.length === 0 && !priorLock)) {
    events.push({ type: "OK", skills: 0, sources: 0, status: "UNCONFIGURED" });
    return { status: "UNCONFIGURED", events, lock: priorLock };
  }

  // staging 目录惰性创建：READY 普通 sync 零网络、零写入（MAT-002），不触碰临时目录。
  let stagingParent = null;
  const ensureStagingParent = async () => {
    stagingParent ??= await fs.mkdtemp(join(tmpdir(), "skills-sync-"));
    return stagingParent;
  };
  try {
    // sources 为空 + 有 v2 lock：期望状态变更，仅 --update 可执行清理（SRC-007 / MAT-012）。
    if (manifest.sources.length === 0) {
      if (!update) {
        throw new SyncError(
          ERR.lockStale,
          `${MANIFEST_REL} declares no sources but ${LOCK_REL} still manages skills; fix: run skills-sync --update to prune managed external skills (built-in skills are never touched).`,
          2,
        );
      }
      const skillsRootAbs = join(root, priorLock.skillsRoot);
      for (const source of priorLock.sources) {
        for (const skill of source.skills) {
          await fs.rm(join(skillsRootAbs, skill.name), { recursive: true, force: true });
          events.push({ type: "PRUNED", name: skill.name });
        }
        await fs.rm(join(skillsRootAbs, SOURCES_DIRNAME, source.id), { recursive: true, force: true });
      }
      await fs.rm(join(root, LOCK_REL), { force: true });
      const gitignorePath = join(priorLock.skillsRoot === "." ? root : join(root, priorLock.skillsRoot), ".gitignore");
      if (await pathExists(fs, gitignorePath)) {
        const raw = await fs.readFile(gitignorePath, "utf8");
        if (raw.startsWith(GITIGNORE_HEADER)) await fs.rm(gitignorePath);
      }
      events.push({ type: "OK", skills: 0, sources: 0, status: "UNCONFIGURED" });
      return { status: "UNCONFIGURED", events, lock: null };
    }

    // NEEDS_UPDATE 边界（LCK-009 / LCK-007）：普通 sync 绝不隐式解析或升级。
    if (!priorLock) {
      if (!update) {
        throw new SyncError(
          ERR.lockMissing,
          `${LOCK_REL} is missing while ${MANIFEST_REL} declares ${manifest.sources.length} source(s); fix: run skills-sync --update to create the first lock.`,
          2,
        );
      }
    } else if (!specsMatch(manifest, priorLock) && !update) {
      throw new SyncError(
        ERR.lockStale,
        `${MANIFEST_REL} source specs differ from ${LOCK_REL}; fix: review the manifest change and run skills-sync --update to re-lock.`,
        2,
      );
    }

    await fs.rm(join(root, manifest.skillsRoot, STAGING_DIRNAME), { recursive: true, force: true }); // MAT-011 残留清理

    // ---- staging：解析与内容准备全部完成前，不修改任何目标状态（MAT-005）----
    const stagedBySourceId = new Map();
    const local = priorLock && specsMatch(manifest, priorLock) ? await assessLocalState({ root, fs, lock: priorLock }) : null;
    const priorById = new Map((priorLock?.sources ?? []).map((source) => [source.id, source]));
    const driftSourceIds = new Set((local?.driftSkills ?? []).map((item) => item.source.id));
    for (const issue of local?.licenseIssues ?? []) driftSourceIds.add(issue.source.id);

    for (const [index, source] of manifest.sources.entries()) {
      const prior = priorById.get(source.id);
      const specUnchanged = prior && sourceSpecEqual(source, prior);
      if (!update) {
        // 普通 sync：resolved 只能来自 lock（MAT-001）；仅在 drift/force 时重新物化。
        const needsStage = force || driftSourceIds.has(source.id);
        if (needsStage) {
          stagedBySourceId.set(source.id, await stageSource({ fs, git, tmpParent: await ensureStagingParent(), index, source, pinnedResolved: prior.resolved }));
        }
        continue;
      }
      // update：解析该次 fetch 观察到的 track tip（RES-002）。
      const staged = await stageSource({ fs, git, tmpParent: await ensureStagingParent(), index, source, pinnedResolved: null });
      const unchanged = !force && specUnchanged && prior.resolved === staged.resolved && local?.ready;
      if (!unchanged) stagedBySourceId.set(source.id, staged);
      if (!staged.licenseDeclared) {
        events.push({
          type: "WARNING",
          code: ERR.licenseMissing,
          message: `source "${source.id}" declares no repository-level LICENSE*; fix: confirm upstream licensing before redistributing.`,
        });
      }
    }

    // 全局唯一性预检（DSC-004）与非受管目录保护（DSC-005），仍在 staging 阶段。
    const effectiveSources = manifest.sources.map((source) => {
      const staged = stagedBySourceId.get(source.id);
      if (staged) return staged;
      return { spec: source, resolved: priorById.get(source.id).resolved, skills: priorById.get(source.id).skills, licenseFiles: priorById.get(source.id).licenseFiles };
    });
    const nameOwners = new Map();
    for (const staged of effectiveSources) {
      for (const skill of staged.skills) {
        const owner = nameOwners.get(skill.name);
        if (owner) {
          throw new SyncError(
            ERR.nameConflict,
            `skill name "${skill.name}" is produced by both "${owner.id}" (path "${owner.sourcePath}") and "${staged.spec.id}" (path "${skill.sourcePath}"); fix: disambiguate with only/exclude in ${MANIFEST_REL}.`,
          );
        }
        nameOwners.set(skill.name, { id: staged.spec.id, sourcePath: skill.sourcePath });
      }
    }

    // .agent/skills/ 冲突检测（DSC-009）：本地 Skill 优先，冲突时报告 diagnostic。
    {
      const syncedNames = new Set(nameOwners.keys());
      const agentConflicts = await checkAgentSkillsConflicts({ root, fs, syncedSkillNames: syncedNames });
      for (const conflict of agentConflicts) {
        events.push({
          type: "WARNING",
          code: ERR.agentSkillsConflict,
          message: `skill name "${conflict.name}" exists in both ${conflict.localDir} (local, takes priority) and in synced source; the local skill will shadow the synced one at runtime.`,
        });
      }
    }

    const skillsRootAbs = join(root, manifest.skillsRoot);
    // 所有权是路径级的（§8.2.6 / MAT-009）：skillsRoot 迁移后，prior lock 只拥有旧根下的目录。
    const rootsMatch = priorLock?.skillsRoot === manifest.skillsRoot;
    const priorNames = new Set(rootsMatch ? (priorLock?.sources ?? []).flatMap((source) => source.skills.map((skill) => skill.name)) : []);
    for (const name of nameOwners.keys()) {
      if (priorNames.has(name)) continue;
      if (await pathExists(fs, join(skillsRootAbs, name))) {
        throw new SyncError(
          ERR.unmanagedConflict,
          `refusing to overwrite ${manifest.skillsRoot}/${name}: it exists but is not managed by the lock; fix: remove or rename the directory by hand, or rename the incoming skill.`,
        );
      }
    }

    // 新 lock（update）或沿用 prior lock（sync 修复）。
    const lock = update
      ? buildLock({
          skillsRoot: manifest.skillsRoot,
          resolvedSources: effectiveSources.map((staged) => ({
            spec: staged.spec,
            resolved: staged.resolved,
            skills: staged.skills,
            licenseFiles: staged.licenseFiles,
          })),
        })
      : priorLock;

    // READY 快路径：零网络（普通 sync）/零写入（update 未变），mtime 保持（MAT-002 / RES-008）。
    if (!update && !force && local?.ready) {
      for (const item of local.keptSkills) events.push({ type: "KEPT", name: item.skill.name, resolved: item.source.resolved });
      events.push({ type: "OK", skills: local.keptSkills.length, sources: lock.sources.length, status: "READY" });
      return { status: "READY", events, lock };
    }
    if (update && !force && stagedBySourceId.size === 0 && local?.ready) {
      for (const source of manifest.sources) {
        const prior = priorById.get(source.id);
        events.push({ type: "UNCHANGED", sourceId: source.id, resolved: prior.resolved });
      }
      for (const item of local.keptSkills) events.push({ type: "KEPT", name: item.skill.name, resolved: item.source.resolved });
      events.push({ type: "OK", skills: local.keptSkills.length, sources: lock.sources.length, status: "UNCHANGED" });
      return { status: "UNCHANGED", events, lock };
    }

    // update 报告（RES-009）：旧/新 SHA、技能增删与摘要变化。
    if (update) {
      for (const source of manifest.sources) {
        if (!stagedBySourceId.has(source.id)) continue;
        const staged = stagedBySourceId.get(source.id);
        const prior = priorById.get(source.id);
        const priorSkills = new Map((prior?.skills ?? []).map((skill) => [skill.name, skill.treeDigest]));
        const nextSkills = new Map(staged.skills.map((skill) => [skill.name, skill.treeDigest]));
        events.push({
          type: "UPDATED",
          sourceId: source.id,
          from: prior?.resolved ?? null,
          to: staged.resolved,
          added: [...nextSkills.keys()].filter((name) => !priorSkills.has(name)),
          removed: [...priorSkills.keys()].filter((name) => !nextSkills.has(name)),
          changed: [...nextSkills.keys()].filter((name) => priorSkills.has(name) && priorSkills.get(name) !== nextSkills.get(name)),
        });
      }
    }

    await commitTransaction({
      root,
      fs,
      lock,
      priorLock,
      stagedBySourceId,
      writeLock: update,
      allowPrune: update,
      events,
    });

    const total = lock.sources.reduce((count, source) => count + source.skills.length, 0);
    const status = update ? "UPDATED" : "SYNCED";
    events.push({ type: "OK", skills: total, sources: lock.sources.length, status });
    if (update) events.push({ type: "NOTE", code: "new-session", message: "Start a new Agent session to load the updated skills." });
    return { status, events, lock };
  } finally {
    if (stagingParent) await fs.rm(stagingParent, { recursive: true, force: true });
    await fs.rm(join(root, manifest.skillsRoot, STAGING_DIRNAME), { recursive: true, force: true });
  }
}


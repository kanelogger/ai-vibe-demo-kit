// exitCode 约定（CLI-007）：2 = manifest/lock/usage/内部契约；1 = 运行时/来源/冲突/校验。
export class SyncError extends Error {
  constructor(code, message, exitCode = 1) {
    super(message);
    this.name = "SyncError";
    this.code = code;
    this.exitCode = exitCode;
  }
}

function configError(message) {
  return new SyncError(ERR.manifestInvalid, message, 2);
}


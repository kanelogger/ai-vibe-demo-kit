export function sha256Hex(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

// entries: [{ path, executable, bytes(Buffer) }]；path 为技能根内 POSIX 相对路径。
export function digestEntries(entries) {
  const sorted = [...entries].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const hash = createHash("sha256");
  for (const entry of sorted) {
    hash.update(entry.path, "utf8");
    hash.update("\0");
    hash.update(entry.executable ? "exec" : "file");
    hash.update("\0");
    hash.update(String(entry.bytes.length));
    hash.update("\0");
    hash.update(entry.bytes);
  }
  return hash.digest("hex");
}

// 磁盘目录摘要；遇到 symlink、socket 或读取失败返回 null（按 drift 处理，由 sync 修复）。
export async function digestDiskDirectory(absDir, fs = defaultFs) {
  const entries = [];
  async function walk(dir, rel) {
    let listing;
    try {
      listing = await fs.readdir(dir, { withFileTypes: true });
    } catch {
      return false;
    }
    for (const item of listing) {
      const itemAbs = join(dir, item.name);
      const itemRel = rel ? `${rel}/${item.name}` : item.name;
      if (item.isDirectory()) {
        if (!(await walk(itemAbs, itemRel))) return false;
        continue;
      }
      if (!item.isFile()) return false; // symlink/socket/fifo：不可复现
      let info;
      let bytes;
      try {
        info = await fs.stat(itemAbs);
        bytes = await fs.readFile(itemAbs);
      } catch {
        return false;
      }
      entries.push({ path: itemRel, executable: (info.mode & 0o111) !== 0, bytes });
    }
    return true;
  }
  if (!(await walk(absDir, ""))) return null;
  return digestEntries(entries);
}


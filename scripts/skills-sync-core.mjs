const MANIFEST_FIELDS = new Set(["version", "description", "skillsRoot", "sources"]);
const SOURCE_FIELDS = new Set(["id", "repo", "path", "track", "only", "exclude"]);
const TRACK_KINDS = new Set(["branch", "tag", "commit"]);

function isNonEmptyString(value) {
  return typeof value === "string" && value.trim() !== "";
}

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function normalizeRelativePath(raw, field, { allowDot }) {
  if (typeof raw !== "string") throw configError(`${field} must be a string; fix: use a project-relative POSIX path.`);
  const trimmed = raw.trim();
  if (trimmed === "") throw configError(`${field} must not be empty; fix: use "." for the repository/project root.`);
  if (trimmed.startsWith("/") || /^[A-Za-z]:/.test(trimmed)) {
    throw configError(`${field} must be relative, got "${trimmed}"; fix: remove the absolute prefix.`);
  }
  if (trimmed.includes("\\")) {
    throw configError(`${field} must use POSIX "/" separators, got "${trimmed}".`);
  }
  const segments = trimmed.split("/").filter((part) => part !== "" && part !== ".");
  if (segments.some((part) => part === "..")) {
    throw configError(`${field} must not contain "..", got "${trimmed}"; fix: keep the path inside the project/repository.`);
  }
  if (segments.length === 0) {
    if (allowDot) return ".";
    throw configError(`${field} must name a directory inside the project, not the project root itself.`);
  }
  return segments.join("/");
}

function normalizePatterns(raw, field) {
  if (raw === undefined) return undefined;
  if (!Array.isArray(raw) || raw.length === 0 || raw.some((item) => !isNonEmptyString(item))) {
    throw configError(`${field} must be a non-empty array of non-empty strings; fix: use skill names or directory prefixes ending in "/".`);
  }
  const items = raw.map((item) => item.trim());
  if (new Set(items).size !== items.length) {
    throw configError(`${field} must not contain duplicates; fix: keep each pattern once.`);
  }
  return [...items].sort();
}

// 解析并严格校验 v2 manifest；抛出 SyncError（manifest-invalid / manifest-version-unsupported）。
export function parseManifestValue(value) {
  if (!isRecord(value)) throw configError("manifest must be a JSON object; fix: see docs/external-skills-sync-requirements.md §10.");
  if (value.version === 1) {
    throw new SyncError(
      ERR.manifestVersion,
      "manifest version 1 is not supported (v2 clean cutover); fix: rewrite sources with track {kind,value} per docs §10 and run skills-sync --update once.",
      2,
    );
  }
  if (value.version !== 2) {
    throw new SyncError(ERR.manifestVersion, `manifest version must be 2, got ${JSON.stringify(value.version)}; fix: set "version": 2.`, 2);
  }
  for (const key of Object.keys(value)) {
    if (!MANIFEST_FIELDS.has(key)) throw configError(`unknown manifest field "${key}"; fix: remove it (allowed: ${[...MANIFEST_FIELDS].join(", ")}).`);
  }
  if (value.description !== undefined && !isNonEmptyString(value.description)) {
    throw configError(`description must be a non-empty string when present.`);
  }
  const skillsRoot =
    value.skillsRoot === undefined
      ? DEFAULT_SKILLS_ROOT
      : normalizeRelativePath(value.skillsRoot, "skillsRoot", { allowDot: false });
  if (!Array.isArray(value.sources)) {
    throw configError(`sources must be an array (use [] to disable external skills).`);
  }
  const ids = new Set();
  const sources = value.sources.map((entry, index) => {
    const at = `sources[${index}]`;
    if (!isRecord(entry)) throw configError(`${at} must be an object.`);
    for (const key of Object.keys(entry)) {
      if (!SOURCE_FIELDS.has(key)) throw configError(`${at} has unknown field "${key}"; fix: remove it (allowed: ${[...SOURCE_FIELDS].join(", ")}).`);
    }
    if (!isNonEmptyString(entry.id) || !SOURCE_ID.test(entry.id.trim())) {
      throw configError(`${at}.id must match ${SOURCE_ID}; fix: use a stable source id like "mattpocock-skills".`);
    }
    const id = entry.id.trim();
    if (ids.has(id)) throw configError(`duplicate source id "${id}"; fix: keep source ids unique.`);
    ids.add(id);
    if (!isNonEmptyString(entry.repo)) throw configError(`${at}.repo must be a non-empty Git remote or local path.`);
    const repo = entry.repo.trim();
    if (/^https?:\/\//i.test(repo)) {
      let url;
      try {
        url = new URL(repo);
      } catch {
        throw configError(`${at}.repo is not a valid URL; fix: use a clone URL without embedded credentials.`);
      }
      if (url.username !== "" || url.password !== "") {
        throw configError(
          `${at}.repo (${url.protocol}//${url.host}/…) embeds credentials; fix: remove userinfo from the URL and configure a Git credential helper or SSH key instead.`,
        );
      }
    }
    const sourcePath = normalizeRelativePath(entry.path, `${at}.path`, { allowDot: true });
    if (!isRecord(entry.track) || !TRACK_KINDS.has(entry.track.kind)) {
      throw configError(`${at}.track.kind must be one of branch|tag|commit; fix: use { "kind": "branch", "value": "main" }.`);
    }
    if (!isNonEmptyString(entry.track.value)) throw configError(`${at}.track.value must be a non-empty string.`);
    const trackValue = entry.track.value.trim();
    if (entry.track.kind === "commit" && !PINNED_SHA.test(trackValue)) {
      throw configError(`${at}.track.value for kind "commit" must be a 40-char lowercase SHA.`);
    }
    if (entry.track.kind !== "commit" && (/[\s~^:?*[\]\\]/.test(trackValue) || trackValue.includes("..") || trackValue.startsWith("-") || trackValue.endsWith("/") || trackValue.endsWith(".lock"))) {
      throw configError(`${at}.track.value "${trackValue}" is not a valid Git ref name.`);
    }
    const only = normalizePatterns(entry.only, `${at}.only`);
    const exclude = normalizePatterns(entry.exclude, `${at}.exclude`);
    return {
      id,
      repo,
      path: sourcePath,
      track: { kind: entry.track.kind, value: trackValue },
      ...(only ? { only } : {}),
      ...(exclude ? { exclude } : {}),
    };
  });
  return { skillsRoot, sources };
}

export function parseManifestText(raw) {
  let value;
  try {
    value = JSON.parse(raw);
  } catch (error) {
    throw configError(`${MANIFEST_REL} is not valid JSON: ${error.message}; fix the JSON syntax.`);
  }
  return parseManifestValue(value);
}


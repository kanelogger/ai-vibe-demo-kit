export class GitError extends Error {
  constructor(args, detail) {
    super(`git ${args.join(" ")}: ${detail}`);
    this.name = "GitError";
    this.args = args;
  }
}

export function createNodeGit({ timeoutMs = 120_000 } = {}) {
  return function git(args, options = {}) {
    return new Promise((resolvePromise, rejectPromise) => {
      execFile(
        "git",
        args,
        {
          cwd: options.cwd,
          env: { ...process.env, GIT_TERMINAL_PROMPT: "0" },
          timeout: options.timeoutMs ?? timeoutMs,
          maxBuffer: 256 * 1024 * 1024,
          encoding: "buffer",
        },
        (error, stdout, stderr) => {
          if (error) {
            const detail =
              typeof stderr === "object" && stderr !== null && stderr.length > 0
                ? stderr.toString("utf8").trim()
                : error.message;
            rejectPromise(new GitError(args, detail));
            return;
          }
          resolvePromise(stdout);
        },
      );
    });
  };
}

async function pathExists(fs, path) {
  try {
    await fs.access(path);
    return true;
  } catch {
    return false;
  }
}

function claudeLinkTarget(name) {
  return `../../.agents/skills/${name}`;
}

async function ensureClaudeDirectory(fs, path, displayPath) {
  try {
    const info = await fs.lstat(path);
    if (!info.isDirectory() || info.isSymbolicLink()) {
      throw new SyncError(
        ERR.claudeLinkConflict,
        `${displayPath} exists but is not a local directory; fix: replace it with a directory, then rerun skills-sync.`,
      );
    }
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
    await fs.mkdir(path);
  }
}

export async function syncClaudeSkillLinks({ root, fs = defaultFs }) {
  const sourceRoot = join(root, DEFAULT_SKILLS_ROOT);
  if (!(await pathExists(fs, sourceRoot))) return { linked: [], unlinked: [] };

  const names = [];
  for (const entry of await fs.readdir(sourceRoot, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    if (await pathExists(fs, join(sourceRoot, entry.name, "SKILL.md"))) names.push(entry.name);
  }
  names.sort();

  const claudeRoot = join(root, ".claude");
  await ensureClaudeDirectory(fs, claudeRoot, ".claude");
  const targetRoot = join(root, CLAUDE_SKILLS_ROOT);
  await ensureClaudeDirectory(fs, targetRoot, CLAUDE_SKILLS_ROOT);
  const expected = new Set(names);
  const linked = [];
  const stale = [];

  for (const entry of await fs.readdir(targetRoot, { withFileTypes: true })) {
    const path = join(targetRoot, entry.name);
    if (!entry.isSymbolicLink()) {
      if (expected.has(entry.name)) {
        throw new SyncError(
          ERR.claudeLinkConflict,
          `${CLAUDE_SKILLS_ROOT}/${entry.name} exists but is not a managed symlink; fix: move or remove it, then rerun skills-sync.`,
        );
      }
      continue;
    }
    const target = await fs.readlink(path);
    const ownedTarget = claudeLinkTarget(entry.name);
    if (expected.has(entry.name)) {
      if (target !== ownedTarget) {
        throw new SyncError(
          ERR.claudeLinkConflict,
          `${CLAUDE_SKILLS_ROOT}/${entry.name} points to an unmanaged target; fix: move or remove it, then rerun skills-sync.`,
        );
      }
      expected.delete(entry.name);
    } else if (target === ownedTarget) {
      stale.push({ name: entry.name, path });
    }
  }

  for (const entry of stale) await fs.rm(entry.path, { force: true });
  for (const name of [...expected].sort()) {
    await fs.symlink(claudeLinkTarget(name), join(targetRoot, name), "dir");
    linked.push(name);
  }
  return { linked, unlinked: stale.map((entry) => entry.name).sort() };
}

